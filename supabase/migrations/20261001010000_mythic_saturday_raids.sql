-- Mythic Saturday Raids: configurable event + lobby + authoritative room state + idempotent rewards.

create table public.raid_events (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  boss_creature_id text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  presentation_timezone text not null default 'America/Sao_Paulo',
  min_players integer not null default 2 check (min_players between 2 and 5),
  max_players integer not null default 5 check (max_players between 2 and 5 and max_players >= min_players),
  recommended_level integer not null default 1 check (recommended_level >= 1),
  boss_config jsonb not null default '{}'::jsonb,
  rewards jsonb not null default '{}'::jsonb,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table public.raid_rooms (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.raid_events(id) on delete cascade,
  host_id uuid not null references public.profiles(id) on delete cascade,
  invite_code text not null unique,
  status text not null default 'lobby'
    check (status in ('lobby', 'active', 'victory', 'defeat', 'closed')),
  state jsonb,
  version integer not null default 0 check (version >= 0),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz
);

create table public.raid_participants (
  room_id uuid not null references public.raid_rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  seat integer not null check (seat between 1 and 5),
  team_snapshot jsonb not null,
  is_ready boolean not null default false,
  presence_status text not null default 'online'
    check (presence_status in ('online', 'loading', 'ready', 'disconnected', 'reconnecting', 'spectator')),
  contribution jsonb not null default '{"actions":0,"damage":0,"healing":0,"shield":0,"buffs":0,"debuffs":0,"terrain":0}'::jsonb,
  joined_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  primary key (room_id, user_id),
  unique (room_id, seat)
);

create table public.raid_actions (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.raid_rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  client_action_id uuid not null,
  action_type text not null,
  payload jsonb not null default '{}'::jsonb,
  result jsonb,
  created_at timestamptz not null default now(),
  unique (room_id, user_id, client_action_id)
);

create table public.raid_room_events (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.raid_rooms(id) on delete cascade,
  sequence integer not null,
  event_type text not null,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  unique (room_id, sequence)
);

create table public.raid_reward_ledger (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.raid_events(id) on delete cascade,
  room_id uuid not null references public.raid_rooms(id) on delete cascade,
  player_id uuid not null references public.profiles(id) on delete cascade,
  reward_id text not null,
  reward_type text not null,
  creature_card_id text,
  granted_at timestamptz not null default now(),
  unique (event_id, player_id, reward_type)
);

create index raid_events_schedule_idx on public.raid_events (starts_at, ends_at) where is_published;
create index raid_rooms_event_status_idx on public.raid_rooms (event_id, status, created_at desc);
create index raid_participants_user_idx on public.raid_participants (user_id, joined_at desc);
create index raid_room_events_room_idx on public.raid_room_events (room_id, sequence);

