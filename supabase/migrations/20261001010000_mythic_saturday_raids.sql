create or replace function public.leave_raid_room(target_room_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  player_id uuid := auth.uid();
  room public.raid_rooms;
begin
  if player_id is null then
    raise exception 'Autenticação necessária' using errcode = '42501';
  end if;
  select * into room from public.raid_rooms where id = target_room_id for update;
  if room.id is null or room.status <> 'lobby' then
    raise exception 'A sala não pode ser abandonada neste momento' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.raid_participants
    where room_id = target_room_id and user_id = player_id
  ) then
    raise exception 'Você não participa desta sala' using errcode = '42501';
  end if;

  delete from public.raid_participants
  where room_id = target_room_id and user_id = player_id;

  if player_id = room.host_id then
    update public.raid_rooms set status = 'closed' where id = target_room_id;
  end if;

  return jsonb_build_object('roomId', target_room_id, 'left', true);
end;
$$;

