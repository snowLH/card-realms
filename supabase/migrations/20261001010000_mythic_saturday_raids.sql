create or replace function public.get_raid_schedule()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', events.id,
    'slug', events.slug,
    'title', events.title,
    'bossCreatureId', events.boss_creature_id,
    'startsAt', events.starts_at,
    'endsAt', events.ends_at,
    'presentationTimezone', events.presentation_timezone,
    'minPlayers', events.min_players,
    'maxPlayers', events.max_players,
    'recommendedLevel', events.recommended_level,
    'bossConfig', events.boss_config,
    'rewards', events.rewards,
    'serverNow', now(),
    'status', case
      when now() < events.starts_at then 'upcoming'
      when now() < events.ends_at then 'active'
      else 'ended'
    end
  ) order by events.starts_at), '[]'::jsonb)
  from public.raid_events events
  where events.is_published
    and events.ends_at >= now() - interval '7 days'
    and events.starts_at <= now() + interval '35 days';
$$;

