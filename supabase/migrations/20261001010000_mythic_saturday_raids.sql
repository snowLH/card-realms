returns trigger
language plpgsql
security definer
set search_path = ''
as $
declare
  target_room_id uuid;
begin
  if tg_op = 'DELETE' then
    target_room_id := old.room_id;
  else
    target_room_id := new.room_id;
  end if;

  perform realtime.broadcast_changes(
    'raid:room:' || target_room_id::text,
    tg_op, tg_op, tg_table_name, tg_table_schema, new, old
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$;

